"""The logistic regressions with full statistical output (as summary(glm(..., family = binomial)) in R).

Model 1 is the scorecard's own regression: default on the WoE values of the 9 characteristics.
Model 2 is a classic logit on the raw variables, for effect sizes in natural units (odds ratios).
Both are fitted on the development years 2007-2014. Run: make regression -> reports/regression.txt
"""

import json

import numpy as np
import pandas as pd

from crs import binning, config, features, target

REPORT_PATH = config.ROOT / "reports" / "regression.txt"


def woe_design(card, X):
    return pd.DataFrame({c["name"]: binning.woe(c, X[c["name"]]) for c in card["characteristics"]}, index=X.index)


def raw_design(X):
    """Natural units; reference levels: mortgage holder, purposes other than credit card and small business."""
    return pd.DataFrame(
        {
            "fico_per_20_points": X["fico"] / 20,
            "log_annual_income": np.log(X["annual_inc"].clip(lower=1000)),
            "dti_per_10_points": X["dti"] / 10,
            "loan_to_income_per_10pct": X["loan_to_income"] * 10,
            "mortgage_accounts": X["mort_acc"].fillna(0).clip(upper=10),
            "inquiries_last_6m": X["inq_last_6mths"].clip(upper=8),
            "revol_util_per_10_points": X["revol_util"] / 10,
            "home_own_outright": (X["home_ownership"] == "OWN").astype(float),
            "home_rent_or_other": X["home_ownership"].isin(["RENT", "OTHER", "ANY", "NONE"]).astype(float),
            "purpose_credit_card": (X["purpose"] == "credit_card").astype(float),
            "purpose_small_business": (X["purpose"] == "small_business").astype(float),
        },
        index=X.index,
    ).dropna()


def odds_ratios(model):
    ci = model.conf_int()
    return pd.DataFrame(
        {"odds ratio": np.exp(model.params), "2.5 %": np.exp(ci[0]), "97.5 %": np.exp(ci[1])}
    ).round(4)


def fit(loans, card_path=config.ROOT / "models" / "scorecard.json"):
    import statsmodels.api as sm  # optional dependency: pip install -e ".[report]"

    card = json.loads(card_path.read_text())
    pop = target.population(loans)
    dev, _ = target.split(pop)
    X, y = features.build(dev), dev["bad"]
    m1 = sm.Logit(y, sm.add_constant(woe_design(card, X))).fit(disp=0)
    D = raw_design(X)
    m2 = sm.Logit(y.loc[D.index], sm.add_constant(D)).fit(disp=0)
    return m1, m2, card


def run(loans, log=print):
    m1, m2, card = fit(loans)
    saved = pd.Series({c["name"]: round(c["coef"], 4) for c in card["characteristics"]}, name="saved scorecard (sklearn)")
    text = "\n\n".join(
        [
            "LOGISTIC REGRESSIONS ON THE DEVELOPMENT YEARS 2007-2014 (generated by `make regression`)",
            "Response: 1 = charged off / default, 0 = fully paid. 36-month loans.",
            "=" * 100 + "\nMODEL 1: the scorecard's regression, inputs = WoE values of the 9 characteristics\n"
            "Read a coefficient as how much of the characteristic's WoE is used: -1 = all of it; between 0 and -1 = part of\n"
            "its effect is already carried by the other characteristics. All must be negative.\n" + "=" * 100,
            str(m1.summary()),
            "Same coefficients as stored in models/scorecard.json (fitted with scikit-learn, almost no penalty):\n"
            + pd.concat([m1.params.drop("const").round(4).rename("statsmodels"), saved], axis=1).to_string(),
            "=" * 100 + "\nMODEL 2: classic logit on the raw variables, for effect sizes\n"
            "Reference: mortgage holder; purposes other than credit card and small business.\n" + "=" * 100,
            str(m2.summary()),
            "Odds ratios with 95 % confidence intervals:\n" + odds_ratios(m2).to_string(),
            "Notes:\n"
            "- With n = 338k every p-value is about 0: significance says little here, effect sizes and the out-of-time Gini matter.\n"
            "- A McFadden pseudo R-squared of about 0.04 is normal for default models: each outcome is a noisy coin flip.\n"
            "  Discrimination (Gini/AUC) is the standard measure.",
        ]
    ) + "\n"
    REPORT_PATH.write_text(text)
    log(text)
    return m1, m2
