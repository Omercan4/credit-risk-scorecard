"""Develop the scorecard on 2007-2014 with time cross-validation, then fit it on all development years.

For each fold (train on the years before the test year, test on that year) the whole recipe runs
on the training years only: binning, selection, regression. Nothing from the test year is seen.
The cross-validation picks how many characteristics the scorecard gets.
"""

import json

import pandas as pd

from crs import binning, config, features, scorecard, target

MAX_FEATURES_GRID = [6, 9, 12]
CARD_PATH = config.ROOT / "models" / "scorecard.json"
REPORT_PATH = config.ROOT / "reports" / "scorecard.md"


def cross_validate(dev, grid=MAX_FEATURES_GRID, log=print):
    X, y = features.build(dev), dev["bad"].to_numpy()
    rows = []
    for test_year, train, test in target.time_folds(dev):
        tr, te = dev.index.get_indexer(train), dev.index.get_indexer(test)
        specs = binning.fit_all(X.iloc[tr], y[tr])
        Xw_tr = binning.transform(specs, X.iloc[tr])
        for k in grid:
            card = scorecard.fit(specs, Xw_tr, y[tr], k)
            s = scorecard.score(card, X.iloc[te])
            rows.append(
                {
                    "test_year": test_year,
                    "train_loans": len(tr),
                    "test_loans": len(te),
                    "max_features": k,
                    "features_used": len(card["characteristics"]),
                    "gini": round(scorecard.gini(y[te], -s), 4),
                }
            )
            log(f"  test {test_year}, up to {k} characteristics: Gini {rows[-1]['gini']:.3f}")
    return pd.DataFrame(rows)


def choose(cv):
    """The grid value with the best mean Gini; within 0.005 of the best, the smaller scorecard wins."""
    mean = cv.groupby("max_features")["gini"].mean()
    return int(min(k for k in mean.index if mean[k] >= mean.max() - 0.005))


def fit_final(dev, max_features):
    X, y = features.build(dev), dev["bad"].to_numpy()
    specs = binning.fit_all(X, y)
    Xw = binning.transform(specs, X)
    card = scorecard.fit(specs, Xw, y, max_features)
    card["fitted_on"] = f"36-month loans issued {dev['year'].min()}-{dev['year'].max()} ({len(dev):,} loans)"
    chosen = [c["name"] for c in card["characteristics"]]
    return card, specs, Xw[chosen]


def run(loans, card_path=CARD_PATH, report_path=REPORT_PATH, log=print):
    pop = target.population(loans)
    dev, _ = target.split(pop)
    log(f"Time cross-validation on {len(dev):,} development loans")
    cv = cross_validate(dev, log=log)
    k = choose(cv)
    log(f"Chosen: up to {k} characteristics. Fitting on all of 2007-2014 ...")
    card, specs, Xw = fit_final(dev, k)
    card["cv"] = cv.to_dict(orient="records")

    card_path.parent.mkdir(parents=True, exist_ok=True)
    card_path.write_text(json.dumps(card, indent=1))
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(report(card, specs, cv, Xw, k))
    log(f"Wrote {card_path} and {report_path}")
    return card, cv


def report(card, specs, cv, Xw, k):
    iv = pd.DataFrame(
        [
            {
                "characteristic": s["name"],
                "IV": s["iv"],
                "in scorecard": "yes" if s["name"] in Xw.columns else "",
            }
            for s in sorted(specs.values(), key=lambda s: -s["iv"])
        ]
    )
    pivot = cv.pivot(index="test_year", columns="max_features", values="gini")
    pivot.columns = [f"up to {c}" for c in pivot.columns]
    pivot.loc["mean"] = pivot.mean()
    coefs = pd.DataFrame(
        {
            "characteristic": [c["name"] for c in card["characteristics"]],
            "coefficient": [round(c["coef"], 3) for c in card["characteristics"]],
            "VIF": scorecard.vif(Xw).to_numpy(),
        }
    )
    pts = scorecard.table(card)
    lo = sum(min(c["points"]) for c in card["characteristics"])
    hi = sum(max(c["points"]) for c in card["characteristics"])
    return "\n\n".join(
        [
            "# Scorecard development (generated by `make scorecard`)",
            f"Fitted on {card['fitted_on']}. Scale: {scorecard.BASE_SCORE} points = odds {scorecard.BASE_ODDS}:1, "
            f"{scorecard.PDO} points double the odds. Possible scores: {lo} to {hi}.",
            "## Time cross-validation (Gini on the test year, training on all earlier years)",
            pivot.round(3).to_markdown(),
            f"Chosen: up to **{k}** characteristics (best mean Gini; a smaller scorecard wins within 0.005).",
            "## Information value of every candidate (all development years)",
            iv.to_markdown(index=False),
            "## Regression: all coefficients negative, as they must be with WoE inputs",
            coefs.to_markdown(index=False),
            "## The scorecard",
            pts.to_markdown(index=False),
        ]
    ) + "\n"
