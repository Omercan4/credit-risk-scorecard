"""Milestone 3.4: the approve/decline rule for the scorecard and the challenger, checked on 2015 money, plus reject bias.

Everything the rule needs (PDs, loss rate) comes from 2007-2014. 2015 only supplies the realised outcome.
"""

import json

import numpy as np
import pandas as pd

from crs import challenger, config, features, rejects, scorecard, strategy, target, validation

REPORT_PATH = config.ROOT / "reports" / "strategy.md"
RESULTS_PATH = config.ROOT / "models" / "strategy.json"
CURVE_PLOT = config.ROOT / "docs" / "img" / "strategy.png"
REJECT_PLOT = config.ROOT / "docs" / "img" / "reject_bias.png"
SCORE_CUTOFFS = list(range(500, 601, 10))
INVESTOR_SHARES = [0.25, 0.5, 0.75]


def run(loans, log=print):
    card = json.loads((config.ROOT / "models" / "scorecard.json").read_text())
    trees = json.loads(validation.RESULTS_PATH.read_text())["challenger_trees"]
    pop = target.population(loans)
    dev, oot = target.split(pop)
    X_dev, X_oot = features.build(dev), features.build(oot)

    log("PDs from 2007-2014 models ...")
    s_oot = scorecard.score(card, X_oot).to_numpy()
    pd_card = scorecard.pd_from_score(s_oot)
    model = challenger.fit(X_dev, dev["bad"].to_numpy(), trees)
    pd_ch = challenger.predict(model, X_oot)
    lgd = strategy.loss_rate(dev)

    approve_card = strategy.expected_profit(oot, pd_card, lgd) > 0
    approve_ch = strategy.expected_profit(oot, pd_ch, lgd) > 0
    same_volume = np.zeros(len(oot), dtype=bool)
    same_volume[np.argsort(pd_ch)[: approve_card.sum()]] = True

    curves = {
        "Scorecard": strategy.curve(oot, pd_card),
        "LightGBM challenger": strategy.curve(oot, pd_ch),
        "Lending Club sub-grade": strategy.curve(oot, validation.subgrade_rank(oot["sub_grade"]).to_numpy()),
    }
    best = {name: c.loc[c["profit_musd"].idxmax()].round(3).to_dict() for name, c in curves.items()}
    rankings = {
        "Scorecard": pd_card,
        "LightGBM challenger": pd_ch,
        "Lending Club sub-grade": validation.subgrade_rank(oot["sub_grade"]).to_numpy(),
    }
    investor = {
        f"fund {int(share * 100)} %": {name: strategy.pick_share(oot, risk, share) for name, risk in rankings.items()}
        for share in INVESTOR_SHARES
    }

    results = {
        "loss_rate_if_default": round(lgd, 4),
        "mean_gain_if_repaid": round(float((strategy.gain_if_repaid(dev) / dev["funded_amnt"]).mean()), 4),
        "oot_2015": {
            "Approve everyone (what was funded)": strategy.outcome(oot, np.ones(len(oot), dtype=bool)),
            "Scorecard rule (expected profit > 0)": strategy.outcome(oot, approve_card),
            "Challenger rule (expected profit > 0)": strategy.outcome(oot, approve_ch),
            "Challenger at the scorecard's approval rate": strategy.outcome(oot, same_volume),
        },
        "hindsight_best": best,
        "investor": investor,
        "investor_50_return_diff": {
            "scorecard minus sub-grade": strategy.bootstrap_return_diff(
                oot, rankings["Scorecard"], rankings["Lending Club sub-grade"], 0.5
            ),
            "challenger minus scorecard": strategy.bootstrap_return_diff(
                oot, rankings["LightGBM challenger"], rankings["Scorecard"], 0.5
            ),
        },
    }

    log("Reject bias ...")
    accepted = loans[loans["issue_d"].dt.year <= rejects.LAST_YEAR]
    rejected = rejects.load()
    comparison = rejects.compare(accepted, rejected)
    results["reject_bias"] = comparison.to_dict()

    table = strategy.score_table(oot, s_oot, SCORE_CUTOFFS)
    RESULTS_PATH.write_text(json.dumps(results, indent=1, default=float))
    REPORT_PATH.write_text(report(results, table, comparison))
    plot_curves(curves, results, CURVE_PLOT)
    plot_rejects(accepted, rejected, REJECT_PLOT)
    log(f"Wrote {RESULTS_PATH}, {REPORT_PATH}, {CURVE_PLOT} and {REJECT_PLOT}")
    return results


def report(results, table, comparison):
    rows = pd.DataFrame(results["oot_2015"]).T
    best = pd.DataFrame(results["hindsight_best"]).T
    return "\n\n".join(
        [
            "# Approve or decline (generated by `make strategy`)",
            f"From 2007-2014: a defaulted loan loses on average **{results['loss_rate_if_default']:.1%}** of the amount lent "
            f"(after what was paid before the default and recoveries); a repaid loan earns on average "
            f"**{results['mean_gain_if_repaid']:.1%}**. Rule: approve when (1 - PD) x gain - PD x loss > 0, "
            "with each loan's own price for the gain. Profit after Lending Club's 1 % fee, not discounted.",
            "## The rules on 2015, counted in real money (million USD)",
            rows.to_markdown(),
            "## With hindsight: the best approval rate for each ranking on 2015",
            "Approving the safest x % by each model's ranking; this uses 2015 outcomes, so it is not a usable rule, "
            "only a measure of how much money each ranking could make.",
            best.to_markdown(),
            "## An investor who can fund only part of the 2015 loans and picks the safest by each ranking",
            "\n\n".join(
                f"### {k}\n\n" + pd.DataFrame(v).T.to_markdown() for k, v in results["investor"].items()
            ),
            "Differences in return on lent when funding 50 %, with 95 % bootstrap intervals (200 resamples):",
            pd.DataFrame(results["investor_50_return_diff"]).T.to_markdown(),
            "## Strategy table: scorecard cut-off scores on 2015",
            table.to_markdown(index=False),
            "## Reject bias: approved vs rejected applicants, 2007-2015",
            comparison.to_markdown(),
        ]
    ) + "\n"


def _plt():
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    return plt


def plot_curves(curves, results, path):
    plt = _plt()
    fig, ax = plt.subplots(figsize=(7.2, 4.6), dpi=150)
    colors = {"Scorecard": "#1f6fb2", "LightGBM challenger": "#5b9a4b", "Lending Club sub-grade": "#888888"}
    for name, c in curves.items():
        ax.plot(c["approval_rate"] * 100, c["profit_musd"], lw=1.8, color=colors[name], label=name)
    rule = results["oot_2015"]["Scorecard rule (expected profit > 0)"]
    ax.scatter([rule["approval_rate"] * 100], [rule["profit_musd"]], color="#1f6fb2", zorder=3, s=30)
    ax.annotate("scorecard rule", (rule["approval_rate"] * 100, rule["profit_musd"]), xytext=(-90, -25),
                textcoords="offset points", fontsize=8, arrowprops={"arrowstyle": "-", "color": "#666666"})
    ax.set(xlabel="approved: the safest x % of 2015 applicants by each ranking", ylabel="realised profit (million USD)",
           xlim=(40, 100))
    lo = min(c.loc[c["approval_rate"] >= 0.4, "profit_musd"].min() for c in curves.values())
    hi = max(c["profit_musd"].max() for c in curves.values())
    ax.set_ylim(lo - (hi - lo) * 0.05, hi + (hi - lo) * 0.08)
    ax.set_title("2015 loans: how much money each ranking makes at each approval rate", fontsize=11)
    ax.legend(frameon=False, fontsize=8, loc="lower center")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path)
    plt.close(fig)


def plot_rejects(accepted, rejected, path):
    plt = _plt()
    acc = ((accepted["fico_range_low"] + accepted["fico_range_high"]) / 2).dropna()
    rej = rejected["risk_score"].dropna()
    bins = np.arange(400, 851, 10)
    fig, ax = plt.subplots(figsize=(7.2, 4.0), dpi=150)
    ax.hist(rej.clip(400, 850), bins=bins, density=True, alpha=0.55, color="#c0504d", label=f"rejected ({len(rej)/1e6:.1f} M)")
    ax.hist(acc.clip(400, 850), bins=bins, density=True, alpha=0.65, color="#1f6fb2", label=f"approved ({len(acc)/1e6:.1f} M)")
    ax.axvline(660, color="#333333", lw=1, ls="--")
    ax.text(655, ax.get_ylim()[1] * 0.92, "the models never saw\nanyone left of here", ha="right", fontsize=8)
    ax.set(xlabel="risk score at application (below 400 shown at 400, above 850 at 850)", ylabel="share of applications",
           yticks=[])
    ax.set_title("Who the scorecard never learned from: rejected applicants 2007-2015", fontsize=11)
    ax.legend(frameon=False, fontsize=8, loc="upper left")
    ax.spines[["top", "right", "left"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)
